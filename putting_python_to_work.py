radius = float(input("Enter the radius of the circle: "))
diameter = 2 * radius
circumference = 2 * 3.14 * radius
area = 3.14 * (radius ** 2)
print("\nCircle Calculations:")
print(f"Diameter: {diameter}")
print(f"Circumference: {circumference}")
print(f"Area: {area}")
